export function getAllDistricts(): string[] {
  const list: string[] = [];
  BANGLADESH_DIVISIONS.forEach((div) => {
    div.districts.forEach((d) => {
      list.push(d.name);
    });
  });
  return list.sort();
}

export function getUpazilasForDistrict(districtName: string): string[] {
  for (const div of BANGLADESH_DIVISIONS) {
    const found = div.districts.find((d) => d.name.toLowerCase() === districtName.toLowerCase());
    if (found) return found.upazilas;
  }
  return ['Sadar'];
}
